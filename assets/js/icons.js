function iconSVG(name, extraClass = "") {
  const ic = ICONS[name];
  if (!ic) return "";
  return ic.t === "fill"
    ? `<svg class="svg-icon ${extraClass}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${ic.body}</svg>`
    : `<svg class="svg-icon ${extraClass}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ic.body}</svg>`;
}
// Replace every <i data-icon="..."> placeholder by its SVG
function renderIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach((el) => {
    el.outerHTML = iconSVG(el.dataset.icon, el.className || "");
  });
}
